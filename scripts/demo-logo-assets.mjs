import fs from 'node:fs';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import * as si from 'react-icons/si';
import * as fa from 'react-icons/fa';
import * as vsc from 'react-icons/vsc';

const names = ['typescript','javascript','dart','java','react','flutter','android','html5','css3','nodedotjs','express','nextdotjs','prisma','amazonaws','postgresql','firebase','nginx','vercel','testinglibrary','jest','cypress','docker','git','jira','github','gitlab','visualstudiocode','androidstudio','sonarqube','figma','microsoft','apple','google','facebook','linkedin','twitter'];
const alternate = {java:fa.FaJava,amazonaws:fa.FaAws,visualstudiocode:vsc.VscVscode,microsoft:fa.FaMicrosoft,twitter:fa.FaTwitter};
const directory = 'public/demo-logos';
fs.mkdirSync(directory,{recursive:true});
for (const name of names) {
  const icon = alternate[name] ?? si[`Si${name[0].toUpperCase()}${name.slice(1)}`];
  if (!icon) throw new Error(`Missing logo: ${name}`);
  fs.writeFileSync(`${directory}/${name}.svg`,renderToStaticMarkup(createElement(icon,{color:'#777777',size:48,xmlns:'http://www.w3.org/2000/svg'})));
}
fs.copyFileSync('node_modules/react-icons/LICENSE',`${directory}/react-icons-LICENSE.txt`);
fs.writeFileSync(`${directory}/ATTRIBUTION.md`, '# Demo logo assets\n\nGenerated by scripts/demo-logo-assets.mjs from the installed react-icons 5.5.0 package. Simple Icons supplies the Si symbols (CC0); Font Awesome supplies Java, AWS, Microsoft and Twitter (CC BY 4.0); VS Code Icons supplies the VS Code mark (CC BY 4.0). Upstream projects: https://simpleicons.org, https://fontawesome.com, https://github.com/microsoft/vscode-codicons. Package license included. Brand marks identify the corresponding products.\n\nThese local files replace unavailable CDN assets in the original Magic UI icon cloud and logo marquee compositions.\n');
console.log(`Wrote ${names.length} local logo assets.`);
